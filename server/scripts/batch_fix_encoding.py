def fix_file(filepath: str) -> tuple[bool, str]:
    """修复单个文件"""
    try:
        # 尝试读取文件
        with open(filepath, encoding='utf-8') as f:
            content = f.read()

        # 检查是否已经是有效的 Python
        try:
            ast.parse(content)
            return True, "文件已经是有效的"
        except SyntaxError:
            pass
        except UnicodeDecodeError:
            pass

        # 应用修复模式
        fixed_content = content
        for pattern, replacement in FIX_PATTERNS:
            fixed_content = re.sub(pattern, replacement, fixed_content)

        # 检查修复后是否有效
        try:
            ast.parse(fixed_content)
            # 保存修复后的文件
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write(fixed_content)
            return True, "修复成功"
        except SyntaxError as e:
            return False, f"无法自动修复: {e}"

    except UnicodeDecodeError:
        # 尝试用其他编码读取
        try:
            with open(filepath, encoding='gbk') as f:
                content = f.read()

            # 应用修复模式
            fixed_content = content
            for pattern, replacement in FIX_PATTERNS:
                fixed_content = re.sub(pattern, replacement, fixed_content)

            # 检查修复后是否有效
            try:
                ast.parse(fixed_content)
                # 保存修复后的文件
                with open(filepath, 'w', encoding='utf-8') as f:
                    f.write(fixed_content)
                return True, "修复成功（从 GBK 转换）"
            except SyntaxError as e:
                return False, f"无法自动修复: {e}"
        except Exception as e:
            return False, f"读取失败: {e}"

    except Exception as e:
        return False, f"处理失败: {e}"


def scan_and_fix_directory(directory: str) -> list[tuple[str, bool, str]]:
    """扫描并修复目录中的所有 Python 文件"""
    results = []

    for root, _dirs, files in os.walk(directory):
        # 跳过虚拟环境
        if 'venv' in root or '.venv' in root or '__pycache__' in root:
            continue

        for f in files:
            if f.endswith('.py'):
                filepath = os.path.join(root, f)

                # 先检查是否有问题
                try:
                    with open(filepath, encoding='utf-8') as fp:
                        content = fp.read()
                    ast.parse(content)
                    # 没有问题，跳过
                    continue
                except SyntaxError:
                    pass
                except UnicodeDecodeError:
                    pass
                except Exception:
                    continue

                # 有问题，尝试修复
                success, message = fix_file(filepath)
                results.append((filepath, success, message))

    return results


if __name__ == "__main__":
    server_dir = os.path.dirname(os.path.abspath(__file__))
    print(f"扫描目录: {server_dir}")
    print("=" * 60)

    results = scan_and_fix_directory(server_dir)

    if results:
        print(f"\n处理了 {len(results)} 个文件:\n")
        success_count = 0
        failed_count = 0
        for filepath, success, message in results:
            status = "✓" if success else "✗"
            print(f"  {status} {filepath}")
            print(f"      {message}")
            if success:
                success_count += 1
            else:
                failed_count += 1

        print(f"\n成功: {success_count}, 失败: {failed_count}")
    else:
        print("\n没有需要修复的文件")
